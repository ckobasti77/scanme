EXHAUST_TIPS = [(0.40, 0.205), (0.52, 0.205)]  # (x, y) levi par; desni je u ogledalu. A09: u zadnjoj maski difuzora, ispod branika
VALANCE = (0.150, 0.266, 0.64, 0.036)  # A09: karbonska zadnja maska difuzora: y dna, y vrha, x pola širine, odmak vrha od zadnje plohe (vrh je iza podvijene ivice branika)
TIP_R = 0.045  # Ø90 mm


def rear_face_z(x: float) -> float:
    return -2.528 + 0.280 * x * x - 0.112 * x ** 4
